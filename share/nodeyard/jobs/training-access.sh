#!/usr/bin/env bash
# nodeyard training access, run on the master.
#
# Adds a second SSH service for remote model training. It:
#   * listens only on the master's Tailscale address (never on the LAN or the internet),
#   * accepts public-key logins only (no passwords, no keyboard-interactive, no root),
#   * accepts only the training user and only keys from the tailnet (100.64.0.0/10),
#   * is opened in ufw, when ufw is active, only on the tailscale0 interface.
# The normal SSH service on port 22 is not changed.
#
#   sudo ./training-access.sh setup  --public-key "$(cat ~/.ssh/id_ed25519.pub)" [--user NAME] [--port 2222]
#   sudo ./training-access.sh status
#   sudo ./training-access.sh remove
#   ./training-access.sh runtime [--venv DIR]       (run as the training user; installs torch and numpy)
#   ./training-access.sh setup --print --public-key "..." --tailscale-ip 100.64.0.10   (prints; writes nothing)
set -euo pipefail

CONF_DIR=/etc/nodeyard
CONF="${CONF_DIR}/sshd_training_config"
UNIT=/etc/systemd/system/nodeyard-training-sshd.service
PIDFILE=/run/nodeyard-training-sshd.pid
TAG="nodeyard-training"

die() { echo "error: $*" >&2; exit 1; }
say() { echo "$*"; }

COMMAND="${1:-status}"
shift || true
PORT=2222
TRAIN_USER="${SUDO_USER:-$(id -un)}"
PUBLIC_KEY=""
TS_IP=""
PRINT_ONLY=0
VENV=""

while [ "$#" -gt 0 ]; do
    case "$1" in
        --port) PORT="$2"; shift 2 ;;
        --user) TRAIN_USER="$2"; shift 2 ;;
        --public-key) PUBLIC_KEY="$2"; shift 2 ;;
        --tailscale-ip) TS_IP="$2"; shift 2 ;;
        --venv) VENV="$2"; shift 2 ;;
        --print) PRINT_ONLY=1; shift ;;
        -h|--help) sed -n '2,15p' "$0"; exit 0 ;;
        *) die "unknown option: $1" ;;
    esac
done

user_home() { eval echo "~$1"; }  # works on Linux and macOS

need_root() {
    if [ "$PRINT_ONLY" -eq 0 ] && [ "$(id -u)" -ne 0 ]; then
        die "this step needs root. Run it with sudo (or add --print to only print the plan)."
    fi
}

check_key() {
    printf '%s\n' "$1" | grep -Eq '^(ssh-ed25519|ssh-rsa|ecdsa-sha2-nistp256|ecdsa-sha2-nistp384) AAAA[0-9A-Za-z+/=]+( .*)?$' \
        || die "--public-key is not a valid SSH public key (expected a line starting with ssh-ed25519 AAAA...)."
}

tailscale_address() {
    if [ -n "$TS_IP" ]; then echo "$TS_IP"; return; fi
    command -v tailscale >/dev/null 2>&1 || die "tailscale is not installed; install and 'tailscale up' first."
    local ip
    ip="$(tailscale ip -4 2>/dev/null | head -n 1 || true)"
    [ -n "$ip" ] || die "Tailscale has no IPv4 address; run 'tailscale up' first."
    echo "$ip"
}

host_key_lines() {
    local key
    for key in /etc/ssh/ssh_host_ed25519_key /etc/ssh/ssh_host_ecdsa_key /etc/ssh/ssh_host_rsa_key; do
        [ -f "$key" ] && echo "HostKey $key"
    done
}

render_config() {
    local ts_ip="$1"
    cat <<EOF
# nodeyard training SSH. Generated by training-access.sh; remove with: training-access.sh remove
Port ${PORT}
ListenAddress ${ts_ip}
$(host_key_lines)
PidFile ${PIDFILE}
PubkeyAuthentication yes
PasswordAuthentication no
KbdInteractiveAuthentication no
PermitRootLogin no
PermitEmptyPasswords no
AuthenticationMethods publickey
AllowUsers ${TRAIN_USER}
AuthorizedKeysFile .ssh/authorized_keys
AllowTcpForwarding no
X11Forwarding no
MaxAuthTries 3
LoginGraceTime 20
UsePAM yes
# File copies (scp, and the runner) use SFTP; internal-sftp needs no extra files on any distro.
Subsystem sftp internal-sftp
EOF
}

render_unit() {
    local sshd_bin
    sshd_bin="$(command -v sshd || echo /usr/sbin/sshd)"
    cat <<EOF
[Unit]
Description=nodeyard training SSH (tailnet only, keys only)
After=network-online.target tailscaled.service
Wants=network-online.target tailscaled.service

[Service]
ExecStartPre=${sshd_bin} -t -f ${CONF}
ExecStart=${sshd_bin} -D -f ${CONF}
Restart=on-failure
RestartSec=5

[Install]
WantedBy=multi-user.target
EOF
}

render_authorized_line() {
    printf 'restrict,from="100.64.0.0/10,fd7a:115c:a1e0::/48" %s %s\n' "$1" "$TAG"
}

setup() {
    need_root
    [ -n "$PUBLIC_KEY" ] || die "--public-key is required (this Mac's public key, for example: cat ~/.ssh/id_ed25519.pub)."
    check_key "$PUBLIC_KEY"
    local ts_ip home_dir auth_file
    ts_ip="$(tailscale_address)"
    home_dir="$(user_home "$TRAIN_USER")"
    [ -n "$home_dir" ] || die "no such user: ${TRAIN_USER}"
    auth_file="${home_dir}/.ssh/authorized_keys"

    if [ "$PRINT_ONLY" -eq 1 ]; then
        say "# --- ${CONF}"; render_config "$ts_ip"
        say "# --- ${UNIT}"; render_unit
        say "# --- ${auth_file} (line added, others kept)"; render_authorized_line "$PUBLIC_KEY"
        local check
        check="$(mktemp)"
        render_config "$ts_ip" > "$check"
        if command -v sshd >/dev/null 2>&1; then
            if sshd -t -f "$check" 2>/dev/null; then say "# sshd accepts the generated config"; else say "# note: sshd -t reported a problem with this machine's host keys or sshd version"; fi
        fi
        rm -f "$check"
        say "# dry run: nothing was written."
        return 0
    fi

    install -d -m 755 "$CONF_DIR"
    render_config "$ts_ip" > "$CONF"
    chmod 644 "$CONF"
    /usr/sbin/sshd -t -f "$CONF" || die "generated sshd config failed its check; nothing was started."

    install -d -m 700 -o "$TRAIN_USER" -g "$(id -gn "$TRAIN_USER")" "${home_dir}/.ssh"
    touch "$auth_file"
    grep -v " ${TAG}\$" "$auth_file" > "${auth_file}.nodeyard.tmp" || true
    render_authorized_line "$PUBLIC_KEY" >> "${auth_file}.nodeyard.tmp"
    mv "${auth_file}.nodeyard.tmp" "$auth_file"
    chown "$TRAIN_USER:$(id -gn "$TRAIN_USER")" "$auth_file"
    chmod 600 "$auth_file"

    render_unit > "$UNIT"
    systemctl daemon-reload
    systemctl enable nodeyard-training-sshd.service
    # restart, not just start: a re-run must pick up a changed config
    systemctl restart nodeyard-training-sshd.service

    if command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q "Status: active"; then
        ufw allow in on tailscale0 to any port "$PORT" proto tcp comment "$TAG" >/dev/null
        # Gloo distributed training rendezvous; the runner binds the selected port
        # to the master tailnet address and removes temporary rules after a job.
        ufw allow in on tailscale0 to any port 29500:29600 proto tcp comment "${TAG}-gloo" >/dev/null
        say "ufw: allowed port ${PORT} on tailscale0 only."
    else
        say "ufw is not active; the service listens only on ${ts_ip}, which is reachable from the tailnet."
    fi
    say "Training SSH is up on ${ts_ip}:${PORT} for user ${TRAIN_USER} (keys only)."
    say "From this Mac: ssh -p ${PORT} ${TRAIN_USER}@${ts_ip}"
}

status() {
    local ts_ip=""
    ts_ip="$(tailscale ip -4 2>/dev/null | head -n 1 || true)"
    echo "config:  $([ -f "$CONF" ] && echo "$CONF" || echo "not set up")"
    echo "service: $(systemctl is-active nodeyard-training-sshd.service 2>/dev/null || echo inactive)"
    echo "tailnet: ${ts_ip:-no tailscale address}"
    if [ -f "$CONF" ]; then
        echo "port:    $(awk '/^Port /{print $2}' "$CONF")"
    fi
    local count=0
    count="$(grep -c " ${TAG}\$" "$(user_home "$TRAIN_USER")/.ssh/authorized_keys" 2>/dev/null || true)"
    echo "keys:    ${count:-0} installed for ${TRAIN_USER}"
}

remove() {
    need_root
    if [ -f "$CONF" ]; then PORT="$(awk '/^Port /{print $2}' "$CONF")"; fi
    systemctl disable --now nodeyard-training-sshd.service 2>/dev/null || true
    rm -f "$UNIT" "$CONF" "$PIDFILE"
    systemctl daemon-reload 2>/dev/null || true
    local home_dir auth_file
    home_dir="$(user_home "$TRAIN_USER")"
    auth_file="${home_dir}/.ssh/authorized_keys"
    if [ -f "$auth_file" ]; then
        grep -v " ${TAG}\$" "$auth_file" > "${auth_file}.nodeyard.tmp" || true
        mv "${auth_file}.nodeyard.tmp" "$auth_file"
        chown "$TRAIN_USER:$(id -gn "$TRAIN_USER")" "$auth_file"
        chmod 600 "$auth_file"
    fi
    if command -v ufw >/dev/null 2>&1; then
        ufw delete allow in on tailscale0 to any port "$PORT" proto tcp >/dev/null 2>&1 || true
        ufw delete allow in on tailscale0 to any port 29500:29600 proto tcp >/dev/null 2>&1 || true
    fi
    say "Training SSH removed. Port 22 was never changed."
}

runtime() {
    # Runs as the training user, not root: a virtual environment with the trainer's dependencies.
    local target="${VENV:-$HOME/nodeyard-train}" index="" package="torch"
    if [ "$(uname -s)" = "Linux" ] && command -v nvidia-smi >/dev/null 2>&1 && nvidia-smi -L >/dev/null 2>&1; then
        target="${VENV:-$HOME/nodeyard-train-cuda}"
        index="--index-url https://download.pytorch.org/whl/cu124"
        package="torch==2.6.0"
    elif [ "$(uname -s)" = "Linux" ]; then
        index="--index-url https://download.pytorch.org/whl/cpu"
    fi
    say "Creating ${target} with ${package} ${index:+($index)}."
    if [ "$PRINT_ONLY" -eq 1 ]; then
        say "python3 -m venv ${target}"
        say "${target}/bin/pip install ${package} numpy ${index}"
        return 0
    fi
    python3 -m venv "$target"
    # shellcheck disable=SC2086
    "${target}/bin/pip" install --upgrade pip >/dev/null
    # shellcheck disable=SC2086
    "${target}/bin/pip" install "$package" numpy ${index}
    say "Runtime ready: ${target}/bin/python"
}

case "$COMMAND" in
    setup) setup ;;
    status) status ;;
    remove) remove ;;
    runtime) runtime ;;
    *) die "unknown command '${COMMAND}'. Use: setup, status, remove, runtime." ;;
esac
